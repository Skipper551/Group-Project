"""retail_base - shared starter module for the `retail_tools` group project.

Every group imports this module. It gives you:
    load_retail()   - loads the Online Retail dataset with correct column types
    basic_clean()   - a MINIMAL cleaning step, so that all groups work on the same numbers
    expect_error()  - a small helper for testing that a function raises an error

Do NOT edit this file - write your own code in your group's module.
"""
import pandas as pd


def load_retail(path="Online_Retail.csv"):
    """Load the Online Retail dataset and add a `Revenue` column.

    WARNING: the data is NOT cleaned - it still contains cancelled invoices,
    negative quantities, zero prices, missing customer IDs, duplicates...

    Args:
        path (str): path to the Online_Retail.csv file

    Returns:
        pd.DataFrame: one row = one product line on an invoice
    """
    df = pd.read_csv(path, encoding="ISO-8859-1",
                     dtype={"InvoiceNo": str, "StockCode": str})
    df["InvoiceDate"] = pd.to_datetime(df["InvoiceDate"], format="%m/%d/%y %H:%M")
    df["Revenue"] = df["Quantity"] * df["UnitPrice"]
    return df


def basic_clean(df):
    """Return a copy of df WITHOUT cancelled invoices, non-positive quantities and prices.

    This is the minimum everybody needs. Group 1 (data quality team) builds
    the full, professional cleaning function.

    Args:
        df (pd.DataFrame): data returned by load_retail()

    Returns:
        pd.DataFrame: cleaned copy (the original df is not changed), index reset
    """
    is_cancelled = df["InvoiceNo"].str.startswith("C")
    keep = (~is_cancelled) & (df["Quantity"] > 0) & (df["UnitPrice"] > 0)
    return df[keep].reset_index(drop=True).copy()


def expect_error(func, *args, error=ValueError, **kwargs):
    """Return True if func(*args, **kwargs) raises `error`; otherwise raise AssertionError.

    Usage in tests:
        assert expect_error(top_products, df, n=-1)
        assert expect_error(top_products, df, by="colour", error=ValueError)
    """
    try:
        func(*args, **kwargs)
    except error:
        return True
    raise AssertionError(f"{func.__name__}{args[1:] if len(args) > 1 else ''} {kwargs} "
                         f"did NOT raise {error.__name__}")
